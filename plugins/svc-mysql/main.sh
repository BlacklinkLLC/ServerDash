esc() { printf '%s' "$1" | tr '\n\r\t' '   ' | sed 's/\\/\\\\/g; s/"/\\"/g'; }
emit_stats() { printf '{"items":[{"label":"%s","value":"%s","hint":"%s","status":"%s"}]}' "$(esc "$1")" "$(esc "$2")" "$(esc "$3")" "$(esc "$4")"; }
value=$(systemctl is-active mysqld 2>/dev/null || systemctl is-active mysql 2>/dev/null || echo unknown)
emit_stats "MySQL Service" "$value" "database unit" "ok"
