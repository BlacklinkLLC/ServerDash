esc() { printf '%s' "$1" | tr '\n\r\t' '   ' | sed 's/\\/\\\\/g; s/"/\\"/g'; }
emit_stats() { printf '{"items":[{"label":"%s","value":"%s","hint":"%s","status":"%s"}]}' "$(esc "$1")" "$(esc "$2")" "$(esc "$3")" "$(esc "$4")"; }
value=$(certbot certificates 2>/dev/null | grep -c 'Certificate Name' || echo 0)
emit_stats "TLS Certificates" "$value" "Managed certificates" "ok"
